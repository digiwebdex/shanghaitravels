import {
  Body,
  Controller,
  Get,
  Headers,
  Param,
  Post,
  Query,
} from "@nestjs/common";
import { Public } from "../rbac";
import { PackagesService } from "./packages.service";

@Public()
@Controller("site/packages")
export class SitePackagesController {
  constructor(private packages: PackagesService) {}

  @Get()
  list(@Query() q: Record<string, string>) {
    return this.packages.siteList(q);
  }

  @Get("search")
  search(@Query() q: Record<string, string>) {
    return this.packages.siteSearch(q);
  }

  @Get(":slug")
  detail(@Param("slug") slug: string) {
    return this.packages.siteDetailBySlug(slug);
  }

  @Post(":slug/enquire")
  enquire(
    @Param("slug") slug: string,
    @Body() dto: any,
    @Headers("x-forwarded-for") fwd?: string,
    @Headers("x-real-ip") realIp?: string,
  ) {
    const ip = (fwd || realIp || "unknown").split(",")[0].trim();
    return this.packages.siteEnquire(slug, dto, ip);
  }
}
